import { relevanceMap, windowsFor, WOEID } from "./constants";
import type { Emotion, Language, Niche, RangeKey, Region, SeedPost, SeedTrend, TrendStatus } from "./types";

type Draft = {
  id: string;
  name: string;
  niche: Niche;
  region: Region;
  language: Language;
  status: TrendStatus;
  growthPct: number;
  windowKey: RangeKey;
  postCount: number;
  uniqueAuthors: number;
  likes: number;
  reposts: number;
  replies: number;
  quotes: number;
  growthRate: number;
  engagementRate: number;
  postVolume: number;
  relevance?: number;
  sentiment: [number, number, number];
  emotion: Emotion;
  summary: string;
  why: string;
  questions: [string, string, string];
  hashtags: string[];
  keywords: string[];
  posts: [string, string, string];
  postSentiment?: ["positive" | "negative" | "neutral", "positive" | "negative" | "neutral", "positive" | "negative" | "neutral"];
};

const SPARK: Record<TrendStatus, number[]> = {
  rising: [8, 10, 14, 18, 28, 40, 62, 100],
  peaking: [30, 48, 70, 88, 100, 96, 90, 84],
  cooling: [40, 70, 100, 90, 76, 60, 48, 36],
};

function postsFor(draft: Draft): SeedPost[] {
  const mood = draft.postSentiment ?? ["neutral", "positive", "neutral"];
  const likes = [120, 86, 54];
  const reposts = [28, 14, 9];
  const replies = [41, 22, 17];
  const quotes = [11, 6, 3];
  return draft.posts.map((text, index) => ({
    text,
    likes: likes[index] + (draft.postCount % 17),
    reposts: reposts[index] + (index === 0 ? 4 : 0),
    replies: replies[index],
    quotes: quotes[index],
    sentiment: mood[index],
    minutesAgo: [18, 47, 96][index],
  }));
}

function build(draft: Draft): SeedTrend {
  return {
    id: draft.id,
    name: draft.name,
    niche: draft.niche,
    region: draft.region,
    language: draft.language,
    status: draft.status,
    growthPct: draft.growthPct,
    windowKey: draft.windowKey,
    postCount: draft.postCount,
    uniqueAuthors: draft.uniqueAuthors,
    likes: draft.likes,
    reposts: draft.reposts,
    replies: draft.replies,
    quotes: draft.quotes,
    growthRate: draft.growthRate,
    engagementRate: draft.engagementRate,
    postVolume: draft.postVolume,
    relevance: relevanceMap(draft.niche, draft.relevance ?? 94),
    sentiment: {
      positive: draft.sentiment[0],
      negative: draft.sentiment[1],
      neutral: draft.sentiment[2],
    },
    emotion: draft.emotion,
    summary: draft.summary,
    why: draft.why,
    questions: [...draft.questions],
    hashtags: draft.hashtags,
    keywords: draft.keywords,
    spark: SPARK[draft.status],
    posts: postsFor(draft),
  };
}

